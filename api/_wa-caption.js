//  api/_wa-caption.js — כיתוב של תמונה שאומר "זו לא הזמנה" (בן, 5/11).
//
//  המקום לאמבט שלחו תמונה עם "אני קונה את המראה ב 114 שח תזכו אותי" — היא
//  נקלטה כסקיצה (L1207) ונמחקה ביד. כיתוב שמדבר על כסף (סכום בש"ח / זיכוי /
//  בלי המילה 'מחיר' לבד — שאלת מחיר עם סקיצה נשארת הזמנה כמו קודם) ואין בו מידה → לא הזמנה: הקליטה סוגרת אותה בלי הזמנה, והסוכנים
//  מטפלים בה כטענת מחיר. כיתוב עם מידה (100x50) — תמיד הזמנה, ליתר ביטחון.
//  משותף לקליטה (_wa-inbound) ולמרכזן (_agent-classify), כדי ששניהם יחליטו אותו דבר.
// ═══════════════════════════════════════════════════════════════════

const MONEY = /\d+(?:[.,]\d+)?\s*(?:ש["״׳']?ח|₪|שקל)|₪\s*\d/;
const CREDIT = /זיכוי|תזכ[והי]|לזכות|זכו אותי|החזר כספי|חויבתי|חייבתם|חייבו אותי/;
const MEASURE = /\d{2,4}\s*(?:[x×X*\/]|על)\s*\d{2,4}/;

const WA_NOT_ORDER_NOTE = 'לא הזמנה — כיתוב על מחיר או זיכוי (עבר לסוכנים)';

function lgWaCaptionNotOrder(caption) {
  const t = String(caption || '').replace(/\s+/g, ' ').trim();
  if (!t || MEASURE.test(t)) return false;
  return MONEY.test(t) || CREDIT.test(t);
}

module.exports = { lgWaCaptionNotOrder, WA_NOT_ORDER_NOTE };
