'use strict';
const assert = require('node:assert/strict');
const { normalizeReading, approvedItems, orderFingerprint, canRead, sourceImage, PROMPT } = require('../api/_sketch-reader');
const catalog = { '8SMH': {name:'שקוף 8 מחוסם',glass:'שקוף',mm:8,proc:'chisum'} };
const row = {label:'דלת',sku:'8SMH',widthMm:811,heightMm:1975,quantity:2,evidence:'רוחב 81.1 למעלה, 80.8 למטה',warnings:[]};
const raw = {rows:[row],warnings:[]};
assert.equal(normalizeReading(raw,catalog).rows[0].widthMm,811);
const unknown = normalizeReading({rows:[{...row,sku:null,widthMm:null,quantity:null}],warnings:[]},catalog);
assert.equal(unknown.rows[0].sku,null);
assert.equal(unknown.rows[0].quantity,null);
assert.ok(unknown.rows[0].warnings.length >= 3);
assert.throws(()=>approvedItems(unknown.rows,catalog));
assert.throws(()=>approvedItems([{...row,sku:'DOES_NOT_EXIST'}],catalog));
assert.throws(()=>approvedItems([{...row,widthMm:1975000}],catalog));
assert.throws(()=>approvedItems([{...row,quantity:1.5}],catalog));
assert.throws(()=>approvedItems([{...row,quantity:501}],catalog));
assert.throws(()=>approvedItems([],catalog));
const items = approvedItems([row],catalog);
assert.equal(items.length,2);
assert.equal(items[0].w,811);
assert.equal(items[0].h,1975);
assert.equal(items[0].chisum,true);
assert.equal(items[0].quantityGroupId,items[1].quantityGroupId);
assert.notEqual(items[0].groupIndex,items[1].groupIndex);
assert.equal(orderFingerprint({items:[{w:1}]}),orderFingerprint({items:[{w:1}]}));
assert.notEqual(orderFingerprint({items:[{w:1}]}),orderFingerprint({items:[{w:2}]}));
assert.notEqual(orderFingerprint({updatedAt:1}),orderFingerprint({updatedAt:2}));
assert.equal(canRead({stage:''}),true);
assert.equal(canRead({stage:'drafter'}),true);
assert.equal(canRead({stage:'opty'}),false);
assert.equal(canRead({stage:'',hashavshevetOrder:{sentAt:1}}),false);
const png='data:image/png;base64,iVBORw0KGgo=';
assert.equal(sourceImage({},png),png);
assert.throws(()=>sourceImage({sketch:png},null)); // no legacy copies: canonical node only
assert.throws(()=>sourceImage({},'https://example.com/image.png'));
assert.throws(()=>sourceImage({},'data:image/svg+xml;base64,AAAA'));
assert.ok(PROMPT.includes('מעטפת'));
assert.ok(PROMPT.includes('null'));
console.log('sketch-reader contracts: PASS');
